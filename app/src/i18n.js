const dict = { ru, uz, en };
let lang = 'ru';

export function setLang(l) { lang = dict[l] ? l : 'ru'; document.documentElement.lang = lang; }
export function getLang() { return lang; }
export function t(key, ...args) {
  const v = dict[lang][key] ?? ru[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}
export function tierName(tier) {
  return t(tier === 'advanced' ? 'tierAdvanced' : tier === 'basic' ? 'tierBasic' : 'tierFree');
}
export function formatDate(iso) {
  const locale = lang === 'en' ? 'en-GB' : lang === 'uz' ? 'uz-Latn-UZ' : 'ru-RU';
  try { return new Date(iso).toLocaleDateString(locale); } catch { return String(iso).slice(0, 10); }
}
